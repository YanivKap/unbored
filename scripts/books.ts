const items: Candidate[] = [];
for (const b of BOOKS) {
  for (const [title, text] of b.ideas) {
    // Each idea needs its own id, but they all link to the same book page.
    const key = `${b.url}#${title}`;
    items.push({
      id: hashId(key),
      title,
      text,
      url: b.url,
      sourceId: "books",
      source: `${b.book} · ${b.author}`,
      tag: "ספרים",
      lang: "he",
      date: "2020-01-01T00:00:00.000Z",
      weight: 9,
      kind: "stock",
    });
  }
}

writeFileSync(
  new URL("../books.json", import.meta.url),
  JSON.stringify({ updated: new Date().toISOString(), items }, null, 1),
);

const short = items.filter((i) => i.text.length < 150);
